    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        if (Paket == null) {
            jTextArea1.setText("Pilih paket dulu!");
            return;
        }

        if (jComboBox1.getSelectedItem() == null) {
            jTextArea1.setText("Pilih kuota dulu!");
            return;
        }

        String kuota = jComboBox1.getSelectedItem().toString();
        harga = 0;

        // HARIAN
        if (Paket.equals("Harian")) {
            if (kuota.equals("5 gb")) harga = 5000;
            else if (kuota.equals("10 gb")) harga = 10000;
            else if (kuota.equals("20 gb")) harga = 20000;
        }

        // MINGGUAN
        else if (Paket.equals("Mingguan")) {
            if (kuota.equals("5 gb")) harga = 20000;
            else if (kuota.equals("10 gb")) harga = 30000;
            else if (kuota.equals("20 gb")) harga = 40000;
        }

        // BULANAN
        else if (Paket.equals("Bulanan")) {
            if (kuota.equals("5 gb")) harga = 50000;
            else if (kuota.equals("10 gb")) harga = 60000;
            else if (kuota.equals("20 gb")) harga = 70000;
        }

        // OUTPUT
        jTextArea1.setText(
            "Paket : " + Paket +
            "\nKuota : " + kuota +
            "\nHarga : Rp " + harga
        );

    }//GEN-LAST:event_jButton1ActionPerformed

