    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        
        if (Paket == null || jComboBox1.getSelectedItem() == null) {
            jTextArea2.setText("Silakan pilih paket dan tampilkan dulu!");
            return;
        }

        if (jComboBox2.getSelectedItem() == null) {
            jTextArea2.setText("Pilih metode pembayaran!");
            return;
        }

        String metode = jComboBox2.getSelectedItem().toString();
        String kuota = jComboBox1.getSelectedItem().toString();

        // Proses transaksi
        if (metode.equals("Cash")) {
            jTextArea2.setText(
                "STRUK PEMBAYARAN" +
                "\nPaket   : " + Paket +
                "\nKuota   : " + kuota +
                "\nHarga   : Rp " + harga +
                "\nMetode  : Cash" +
                "\nStatus  : Lunas" +
                "\nTerima kasih!"
            );
        } 

        else if (metode.equals("Qris")) {
            jTextArea2.setText(
                "STRUK PEMBAYARAN" +
                "\nPaket   : " + Paket +
                "\nKuota   : " + kuota +
                "\nHarga   : Rp " + harga +
                "\nMetode  : QRIS" +
                "\nSilakan scan QR untuk bayar" +
                "\nStatus  : Menunggu Pembayaran"
            );
        }
    }//GEN-LAST:event_jButton2ActionPerformed

